#!/bin/sh
# Create a ready-to-use .env.mesh for one enrolled Erugo mesh node.
# Run this on EACH host from the repository root.
set -eu

cd "$(dirname "$0")/.."

if [ -f .env.mesh ]; then
    echo "ERROR: .env.mesh already exists. Edit it directly or move it aside first." >&2
    exit 1
fi

printf 'Mesh node id (lowercase letters, digits, - or _; e.g. coordinator, peer1, peer2, peer3): '
read -r NODE_ID

if ! printf '%s' "$NODE_ID" | grep -Eq '^[a-z][a-z0-9_-]{1,63}$'; then
    echo "ERROR: node id must start with a lowercase letter and be 2-64 characters of lowercase letters, digits, - or _." >&2
    exit 1
fi

printf 'Public HTTPS URL of THIS host (e.g. https://peer1.example.com): '
read -r DATA_URL

printf 'Coordinator API URL reachable FROM THIS HOST (e.g. https://share.example.com): '
read -r COORD_URL

printf 'Bind address for the app port [127.0.0.1:18090]: '
read -r BIND
BIND=${BIND:-127.0.0.1:18090}

if [ -z "$DATA_URL" ] || [ -z "$COORD_URL" ]; then
    echo "ERROR: both URLs are required." >&2
    exit 1
fi

case "$DATA_URL" in
    https://*) ;;
    *) echo "ERROR: data URL must start with https://." >&2; exit 1 ;;
esac

APP_KEY="base64:$(openssl rand -base64 32)"
JWT_SECRET="$(openssl rand -hex 32)"
# Enrolled peers use Ed25519. This value is only a random placeholder for the
# legacy HMAC fallback and is intentionally different on every host.
LEGACY_SECRET="$(openssl rand -hex 32)"

cat > .env.mesh <<EOF
# Generated by scripts/mesh-bootstrap.sh. APP_KEY/JWT_SECRET are unique to this
# host. MESH_SECRET is only the legacy fallback; enrolled peers do not use it.
# Keep this file mode 600 and out of git.

APP_ENV=production
APP_DEBUG=false
APP_URL=${DATA_URL}
APP_KEY=${APP_KEY}
JWT_SECRET=${JWT_SECRET}

MESH_ENABLED=true
MESH_SECRET=${LEGACY_SECRET}
MESH_NODE_ID=${NODE_ID}
MESH_NODES='{"${NODE_ID}":"${DATA_URL}"}'
MESH_COORDINATOR_URL=${COORD_URL}
MESH_BIND=${BIND}
TRUSTED_PROXIES=

MESH_CHUNK_SIZE=8388608
MESH_WRITE_COPIES=2
MESH_TOKEN_TTL=300
MESH_MAX_TOKEN_TTL=900

GIT_SHA=dev
INSTALL_ASR=0
EOF

chmod 600 .env.mesh

echo
echo "Wrote .env.mesh (mode 600) for node '${NODE_ID}'."
echo "Bind: ${BIND} (container port 80). Public traffic normally enters on"
echo "443 via a tunnel/proxy that forwards to this address."
echo "MESH_NODES currently lists only this node. On the coordinator, edit it"
echo "to list every peer's public HTTPS URL before creating upload intents."
echo
echo "Next steps:"
echo "  sudo docker compose --env-file .env.mesh -p erugo-mesh-node \\"
echo "    -f docker-compose.mesh-node.yml up -d --build"
echo "  sudo docker compose --env-file .env.mesh -p erugo-mesh-node \\"
echo "    -f docker-compose.mesh-node.yml exec app php artisan mesh:peer-init ${NODE_ID} ${DATA_URL}"
echo
echo "Copy the printed blob into Settings -> Mesh on the coordinator."
echo "No shared secret needs to be copied between hosts."
