#!/bin/sh
# Create a ready-to-use .env.mesh for one Erugo mesh node.
# Run this on EACH host from the repository root.
set -eu

cd "$(dirname "$0")/.."

if [ -f .env.mesh ]; then
    echo "ERROR: .env.mesh already exists. Edit it directly or move it aside first." >&2
    exit 1
fi

printf 'Mesh node id (coordinator|peer1|peer2): '
read -r NODE_ID

case "$NODE_ID" in
    coordinator|peer1|peer2) ;;
    *) echo "ERROR: node id must be coordinator, peer1 or peer2." >&2; exit 1 ;;
esac

printf 'Private IP or hostname of THIS host (the gateway will connect here): '
read -r PEER_HOST

printf 'Coordinator API URL reachable FROM THIS HOST (e.g. http://100.x.y.z:8090): '
read -r COORD_URL

printf 'Shared mesh secret (same exact value on all instances): '
# POSIX sh has no `read -s`; hide input only when attached to a terminal.
stty -echo 2>/dev/null || true
read -r SHARED_SECRET
stty echo 2>/dev/null || true
echo

if [ -z "$PEER_HOST" ] || [ -z "$COORD_URL" ] || [ -z "$SHARED_SECRET" ]; then
    echo "ERROR: all values are required." >&2
    exit 1
fi

APP_KEY="base64:$(openssl rand -base64 32)"
JWT_SECRET="$(openssl rand -hex 32)"
MESH_BIND="${PEER_HOST}:8090"

cat > .env.mesh <<EOF
# Generated by scripts/mesh-bootstrap.sh. MESH_SECRET is shared; all other
# secrets are unique to this host. Keep this file mode 600 and out of git.

APP_ENV=production
APP_DEBUG=false
APP_URL=${COORD_URL}
APP_KEY=${APP_KEY}
JWT_SECRET=${JWT_SECRET}

MESH_SECRET=${SHARED_SECRET}
MESH_NODE_ID=${NODE_ID}
MESH_NODES='{"peer1":"http://peer1:80","peer2":"http://peer2:80"}'
MESH_COORDINATOR_URL=${COORD_URL}
MESH_BIND=${MESH_BIND}
TRUSTED_PROXIES=

MESH_CHUNK_SIZE=8388608
MESH_WRITE_COPIES=2
MESH_TOKEN_TTL=300
MESH_MAX_TOKEN_TTL=900

GIT_SHA=dev
INSTALL_ASR=0
EOF

chmod 600 .env.mesh

echo
echo "Wrote .env.mesh (mode 600) for node '${NODE_ID}'."
echo "Shared-secret fingerprint (must match on every host):"
grep '^MESH_SECRET=' .env.mesh | sha256sum
echo
echo "Next steps:"
echo "  sudo docker compose --env-file .env.mesh -p erugo-mesh-node \\"
echo "    -f docker-compose.mesh-node.yml up -d --build"
echo "  curl -sS http://127.0.0.1:8090/n/${NODE_ID}/health"
echo
echo "For peers, point the gateway at http://${PEER_HOST}:8090 and, if this is"
echo "peer1, stop the local peer1 container on the gateway host."
